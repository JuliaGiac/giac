#!/usr/bin/env node
// Copy giac-openmath's table and shared corpus at a commit into giac-wasm:
//   node scripts/update-openmath.mjs <commit>
// writes src/openmath-table.mjs (the table, its commits and SHA-256) and
// test/fixtures/openmath-to-giac.json. The table at <commit> must be the one
// the corpus was written for (its table_commit), byte for byte.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const source = process.argv[2];
if (!/^[0-9a-f]{40}$/.test(source ?? '')) {
  console.error('usage: node scripts/update-openmath.mjs <40-character commit of JuliaGiac/giac-openmath>');
  process.exit(1);
}
const raw = (commit, path) => `https://raw.githubusercontent.com/JuliaGiac/giac-openmath/${commit}/${path}`;
const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
};

const corpusText = await get(raw(source, 'test/fixtures/openmath-to-giac.json'));
const corpus = JSON.parse(corpusText);
const tableText = await get(raw(source, 'giac-openmath.json'));
const tableAtCorpus = await get(raw(corpus.table_commit, 'giac-openmath.json'));
if (tableText !== tableAtCorpus) {
  throw new Error(`the table at ${source} differs from the one the corpus was written for (${corpus.table_commit})`);
}
const sha256 = createHash('sha256').update(tableText).digest('hex');
const table = JSON.parse(tableText);

writeFileSync(new URL('../src/openmath-table.mjs', import.meta.url),
  `// The giac-openmath table, embedded: generated by scripts/update-openmath.mjs.
// Source: https://github.com/JuliaGiac/giac-openmath/blob/${source}/giac-openmath.json
// Do not edit by hand: change the table there, then run the script with its commit.
export default ${JSON.stringify({ source, commit: corpus.table_commit, sha256, ...table })};
`);
writeFileSync(new URL('../test/fixtures/openmath-to-giac.json', import.meta.url), corpusText);
console.log(`giac-openmath ${source.slice(0, 7)} (table ${corpus.table_commit.slice(0, 7)}, sha256 ${sha256.slice(0, 12)}): ${corpus.cases.length} cases`);
